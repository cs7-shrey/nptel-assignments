// Fisher-Yates. Pass a seeded random when the order must match between the server and the browser.
export function shuffle<T>(items: readonly T[], random: () => number = Math.random): T[] {
  const list = [...items];
  for (let i = list.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [list[i], list[j]] = [list[j], list[i]];
  }
  return list;
}

// mulberry32: a small seeded generator, so one seed always produces one order.
export function seededRandom(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// A stable seed for any text, such as a course id, so each course mixes its own questions.
export function seedFrom(text: string): number {
  let hash = 2166136261;
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

// A fresh seed for a reshuffle; never 0, which is reserved for the stable order.
export const randomSeed = () => Math.floor(Math.random() * 0xffffffff) || 1;
